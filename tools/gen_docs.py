def md_cell(text: str) -> str:
    """Escape a regex so it survives a markdown table cell."""
    return text.replace("|", "\\|")


#: the keyword-lookahead group ``rules._not_keyword`` builds: an alternation
#: of bare words followed by ``(?![-\w])``. Its source is a *set*, so the order
#: the words come out in changes from process to process -- which would make
#: this file un-regeneratable. Longest-first is the only ordering that matters
#: for matching, so equal-length words are put in alphabetical order here.
_ALT_WORD = r"(?:[\w.+-]+|\\d\+)"
_KEYWORD_ALT = re.compile(
    rf"\(\?:({_ALT_WORD}(?:\|{_ALT_WORD})+)\)\(\?!\[-\\w\]\)")


def _stable_alt(m: re.Match) -> str:
    words = sorted(m.group(1).split("|"), key=lambda w: (-len(w), w))
    return "(?:" + "|".join(words) + r")(?![-\w])"


def pattern_cell(pattern: str) -> str:
    """One regex, collapsed onto one line and readable in a table cell."""
    out = _KEYWORD_ALT.sub(_stable_alt, pattern)
    out = md_cell(out.replace(ENC, "<ENC>").replace(VAL, "<VAL>"))
    return re.sub(r"\s+", " ", out).strip()


def family_counts() -> str:
    counts = Counter(family_of(name) for name in rule_names())
    return ", ".join(f"{counts[f]} `{f}`" for f in RULE_FAMILIES if counts[f])


