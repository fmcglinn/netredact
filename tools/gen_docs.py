def address_classes_table() -> tuple[str, str]:
    out = ["| Class | Prefixes | RFC | Description |", "|---|---|---|---|"]
    for name, prefixes, rfc, desc in V4_CLASSES:
        out.append(f"| `{name}` | {', '.join(f'`{p}`' for p in prefixes)} "
                   f"| {rfc} | {desc} |")
    out.append("| `well_known` | the addresses in `well_known_resolvers` | -- "
               "| public resolvers |")
    out.append("| `other_unicast` | everything else | -- "
               "| globally routable space |")
    v6 = ["| Class | Prefixes | RFC | Description |", "|---|---|---|---|"]
    for name, prefixes, rfc, desc in V6_CLASSES:
        v6.append(f"| `{name}` | {', '.join(f'`{p}`' for p in prefixes)} "
                  f"| {rfc} | {desc} |")
    v6.append("| `well_known` | the addresses in `well_known_resolvers` | -- "
              "| public resolvers |")
    v6.append("| `other_unicast` | everything else | -- | global unicast |")
    return "\n".join(out), "\n".join(v6)


def classes_md() -> str:
    v4, v6 = address_classes_table()
    return "\n".join([
        BANNER, "# Address classes\n",
        "Every address netredact sees is put into exactly **one** class. The",
        "classes are mutually exclusive and checked most-specific first, so one",
        "key in `[ipv4]` or `[ipv6]` governs any given address with no",
        "ambiguity. `default` covers every class you do not name, which is what",
        "makes the partition complete.\n",
        "Each class takes an action: `keep`, `pseudo`, `hash` or `redact`.",
        "`pseudo` moves the address inside a pool and preserves the equality",
        "relation; `hash` writes `<IP-a1b2c3>` / `<IP6-a1b2c3>`; `redact` writes",
        "the RFC-reserved constant `192.0.2.0` / `2001:db8::`, which destroys it.\n",
        "There is deliberately no `rfc5735` class. RFC 5735 is a *set* of these",
        "ranges, so a single key for it would overlap `rfc1918`, `loopback`,",
        "`multicast` and others, and the precedence between them would be",
        "arbitrary. Each range is named for what it is instead.\n",
        "## IPv4 -- `[ipv4]`\n", v4,
        "\n## IPv6 -- `[ipv6]`\n", v6,
        "\n## Always exempt\n",
        "**Netmasks and wildcard masks are never touched**, whatever you set.",
        "They are detected structurally: a dotted quad is treated as a mask when",
        "either it or its complement is of the form `1*0*`, which covers",
        "`255.255.255.0`, `0.0.0.255`, `0.0.0.0` and `255.255.255.255`.",
        "Substituting a mask would break the configuration.\n",
        "`keep_networks` is an escape hatch on top of the classes: prefixes",
        "listed there survive even when their class acts -- useful to keep one",
        "management prefix readable.\n",
        "## How pseudonyms are allocated\n",
        "IPv4 keeps its **host octet and prefix length**; only the /24 moves, into",
        "`[ipv4] pool` (default `198.18.0.0/15` then `100.64.0.0/10`). Two",
        "addresses that shared a /24 still share one afterwards, so link",
        "adjacencies and ACLs continue to make sense.\n",
        "IPv6 keeps its **interface identifier**; only the /64 moves, into",
        "`[ipv6] pool` (default `2001:db8::/32`).\n",
        "### Pool capacity is a hard limit\n",
        "One /24 of pool is consumed per **distinct source /24**, for as long as",
        "the run lasts. A pool entry holds `1 << (24 - prefixlen)` of them:",
        "a `/15` is 512, a `/10` is 16384, and the default",
        "`[\"198.18.0.0/15\", \"100.64.0.0/10\"]` is 16896. IPv6 is counted the",
        "same way in /64s: `1 << (64 - prefixlen)`, so the default `/32` holds",
        "4.3 billion and is never the constraint.\n",
        "Run out and the run **fails outright** --",
        "`RuntimeError: exhausted the v4net pseudonym space` -- rather than",
        "reusing a pseudonym and silently merging two subnets. A large",
        "service-provider configuration can easily carry more than 512 distinct",
        "/24s, so a pool narrowed to one `/15` is not enough for one: size the",
        "pool for the biggest file you will feed it, not the one in front of",
        "you.\n",
        "The two pressures pull in opposite directions. A wider pool is more",
        "capacity; a narrower one is less chance of overlapping space the",
        "configuration really uses. Acting on the overlapping *class* resolves",
        "both at once -- with `cgnat` pseudonymised, no real CGNAT address is",
        "left in the output to be confused with a generated one, so the full",
        "`100.64.0.0/10` is free to be pool.\n",
        "### Pool collisions\n",
        "The default IPv4 pool includes `100.64.0.0/10`. If your configuration",
        "really uses CGNAT and `cgnat` is left at `keep`, the output will contain",
        "real and generated addresses that look alike. netredact detects this and",
        "warns, naming both fixes: move the pool with",
        "`pool = [\"198.18.0.0/15\"]`, or give `cgnat` an action so that space",
        "moves too.\n",
        "It is also why a second pass over already-pseudonymised output",
        "**re-maps** pool addresses instead of leaving them alone: treating a",
        "pool address as \"already done\" would leak a real CGNAT address that",
        "happened to land in the pool. So `hash` and `redact` are fully",
        "idempotent -- their output is recognisably netredact's -- while `pseudo`",
        "on an address or a MAC is not: the substitute is deliberately",
        "indistinguishable from a real value, including to netredact itself.\n",
    ])


def annotated_toml() -> str:
    return TOML_BANNER + Config().to_toml()


TARGETS = {
    "docs/rules.md": rules_md,
    "docs/address-classes.md": classes_md,
    "docs/examples/annotated.toml": annotated_toml,
}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if any generated file is out of date")
    args = ap.parse_args()

    stale = []
    for rel, fn in TARGETS.items():
        path = ROOT / rel
        wanted = fn()
        current = path.read_text() if path.exists() else None
        if current == wanted:
            continue
        if args.check:
            stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(wanted)
            print(f"wrote {rel}")
    if stale:
        print("out of date: " + ", ".join(stale), file=sys.stderr)
        print("run: python tools/gen_docs.py", file=sys.stderr)
        return 1
    if args.check:
        print("docs up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
